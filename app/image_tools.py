"""Image generation tools for SavoryBalance meals and dishes using Gemini."""

import json
import re
import uuid
from google import genai
from google.adk.tools.tool_context import ToolContext
from google.cloud import storage
from google.genai import types

PROJECT_ID = "qwiklabs-gcp-04-18d3e33b1a42"
BUCKET_NAME = "savory-balance-media-qwiklabs-gcp-04-18d3e33b1a42"
MODEL_NAME = "gemini-3.1-flash-lite-image"

_genai_client = None
_storage_client = None


def get_genai_client() -> genai.Client:
    """Returns singleton genai Client configured for Vertex AI in global location."""
    global _genai_client
    if _genai_client is None:
        _genai_client = genai.Client(
            vertexai=True,
            project=PROJECT_ID,
            location="global",
        )
    return _genai_client


def get_storage_client() -> storage.Client:
    """Returns singleton Google Cloud Storage client."""
    global _storage_client
    if _storage_client is None:
        _storage_client = storage.Client(project=PROJECT_ID)
    return _storage_client


async def generate_dish_image(tool_context: ToolContext, dish_name: str, visual_description: str = "") -> str:
    """Generates a high-quality photo preview of a healthy savory meal or recipe using Gemini.

    Saves the image as an artifact for the Playground and uploads it to Cloud Storage,
    returning its public HTTPS URL.

    Args:
        tool_context: ADK ToolContext to access save_artifact.
        dish_name: Name of the dish (e.g. 'Avocado & Poached Egg Protein Bowl').
        visual_description: Optional extra details to guide presentation, plating, and lighting.

    Returns:
        JSON string containing the public image URL, filename, and artifact status.
    """
    clean_name = re.sub(r"[^a-zA-Z0-9_-]+", "-", dish_name.strip().lower()).strip("-")
    filename = f"{clean_name}-{uuid.uuid4().hex[:8]}.jpg"

    prompt = (
        f"Professional food photography of {dish_name}. {visual_description}. "
        "Appetizing, fresh, healthy savory whole-food dish, studio lighting, elegant tableware, "
        "shallow depth of field, 4k detail, no artificial sweets or sugar."
    )

    client = get_genai_client()

    try:
        response = client.models.generate_content(
            model=MODEL_NAME,
            contents=prompt,
            config=types.GenerateContentConfig(
                response_modalities=["IMAGE"],
                image_config=types.ImageConfig(aspect_ratio="1:1"),
            ),
        )

        image_bytes = None
        mime_type = "image/jpeg"

        if response.candidates and response.candidates[0].content and response.candidates[0].content.parts:
            for part in response.candidates[0].content.parts:
                if part.inline_data and part.inline_data.data:
                    image_bytes = part.inline_data.data
                    mime_type = part.inline_data.mime_type or mime_type
                    break

        if not image_bytes:
            return json.dumps({"status": "error", "message": "No image data was generated by the model."})

        # 1. Save artifact for Playground's Artifacts panel
        artifact_part = types.Part.from_bytes(data=image_bytes, mime_type=mime_type)
        try:
            await tool_context.save_artifact(filename=filename, artifact=artifact_part)
            artifact_saved = True
        except Exception as e:
            # Artifact service might not be configured in non-playground test runs
            artifact_saved = False

        # 2. Upload image bytes directly to public GCS bucket
        gcs_client = get_storage_client()
        bucket = gcs_client.bucket(BUCKET_NAME)
        blob = bucket.blob(filename)
        blob.upload_from_string(image_bytes, content_type=mime_type)

        public_url = f"https://storage.googleapis.com/{BUCKET_NAME}/{filename}"

        return json.dumps({
            "status": "success",
            "dish_name": dish_name,
            "filename": filename,
            "artifact_saved": artifact_saved,
            "image_url": public_url,
        }, indent=2)

    except Exception as e:
        return json.dumps({"status": "error", "message": f"Failed to generate or upload image: {str(e)}"})
